// =====================================================
// 💾 EXPORT CHAT
// =====================================================

document
  .getElementById("exportBtn")
  .onclick =
  () => {

    const text =
      [
        ...document.querySelectorAll(
          ".message"
        )
      ]

      .map(
        (message) =>
          message.innerText
      )

      .join("\n\n");


    const blob =
      new Blob(
        [text],
        {
          type:
            "text/plain"
        }
      );


    const url =
      URL.createObjectURL(
        blob
      );


    const link =
      document.createElement(
        "a"
      );

    link.href =
      url;

    link.download =
      "KirongAI_Chat.txt";

    link.click();


    URL.revokeObjectURL(
      url
    );

  };


// =====================================================
// 📍 LOCATION
// =====================================================

document
  .getElementById("locationBtn")
  .onclick =
  () => {

    if (
      !navigator.geolocation
    ) {

      addMessage(
        "Location is not supported by this browser.",
        "ai"
      );

      return;

    }


    navigator
      .geolocation
      .getCurrentPosition(

        (position) => {

          const latitude =
            position.coords.latitude
              .toFixed(4);

          const longitude =
            position.coords.longitude
              .toFixed(4);


          addMessage(

            `📍 Latitude: ${latitude}<br>
             Longitude: ${longitude}`,

            "ai"

          );

        },

        () => {

          addMessage(
            "📍 I could not access your location.",
            "ai"
          );

        }

      );

  };


