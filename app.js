const themeBtn =
  document.getElementById("themeBtn");

const thinking =
  document.getElementById("thinking");

let chatHistory = [];


// =====================================================
// 💬 ADD MESSAGE
// =====================================================

function addMessage(text, sender) {

  const message =
    document.createElement("div");

  message.className =
    `message ${sender}`;

  message.innerHTML =
    `<p>${text}</p>`;

  chatBox.appendChild(message);

  chatBox.scrollTop =
    chatBox.scrollHeight;
}


// =====================================================
// 🖼️ ADD IMAGE
// =====================================================

function addImage(image, caption = "") {

  const message =
    document.createElement("div");

  message.className =
    "message ai";

  message.innerHTML = `

    ${
      caption
        ? `<p>${caption}</p>`
        : ""
    }

    <img
      src="${image}"
      alt="Kirong AI generated image"
      style="
        display:block;
        width:100%;
        max-width:500px;
        margin-top:12px;
        border-radius:18px;
        box-shadow:0 15px 40px rgba(0,0,0,.35);
      "
    >

    <div style="
      display:flex;
      gap:10px;
      margin-top:12px;
      flex-wrap:wrap;
    ">

      <a
        href="${image}"
        download="KirongAI_Generated.png"
        style="text-decoration:none;"
      >

        <button
          style="
            padding:10px 15px;
            border:none;
            border-radius:12px;
            cursor:pointer;
          "
        >
          📥 Save Image
        </button>

      </a>

      <button
        onclick="window.open('${image}', '_blank')"
        style="
          padding:10px 15px;
          border:none;
          border-radius:12px;
          cursor:pointer;
        "
      >
        🔍 Open
      </button>

    </div>

  `;

  chatBox.appendChild(message);

  chatBox.scrollTop =
    chatBox.scrollHeight;
}


// =====================================================
// 🧠 THINKING
// =====================================================

function showThinking() {

  thinking.classList.remove(
    "hidden"
  );

}

function hideThinking() {

  thinking.classList.add(
    "hidden"
  );

}


// =====================================================
// 🚀 SEND MESSAGE
// =====================================================

async function sendMessage() {

  const text =
    userInput.value.trim();

  if (!text) return;


  // ---------------------------------------------------
  // USER MESSAGE
  // ---------------------------------------------------

  addMessage(
    text,
    "user"
  );

  userInput.value = "";

  showThinking();


  try {

    // -------------------------------------------------
    // LANGUAGE
    // -------------------------------------------------

    const languageSelect =
      document.getElementById(
        "languageSelect"
      );

    const language =
      languageSelect
        ? languageSelect.value
        : "English";


    // -------------------------------------------------
    // API REQUEST
    // -------------------------------------------------

    const response =
      await fetch(
        "/api/chat",
        {

          method: "POST",

          headers: {
            "Content-Type":
              "application/json"
          },

          body:
            JSON.stringify({

              message:
                text,

              history:
                chatHistory,

              language:
                language

            })

        }
      );


    const data =
      await response.json();


    hideThinking();


    // -------------------------------------------------
    // ERROR
    // -------------------------------------------------

    if (
      !response.ok
    ) {

      addMessage(
        data.text ||
        "⚠️ Something went wrong.",
        "ai"
      );

      return;
    }


    // -------------------------------------------------
    // 🎨 IMAGE RESPONSE
    // -------------------------------------------------

    if (
      data.type === "image" &&
      data.image
    ) {

      addImage(
        data.image,
        data.text ||
        "🎨 Image generated by Kirong AI."
      );

      return;
    }


    // -------------------------------------------------
    // 💬 TEXT RESPONSE
    // -------------------------------------------------

    addMessage(
      data.text ||
      "⚠️ Kirong AI returned no response.",
      "ai"
    );


    // -------------------------------------------------
    // HISTORY
    // -------------------------------------------------

    chatHistory.push({

      role:
        "user",

      content:
        text

    });


    chatHistory.push({

      role:
        "assistant",

      content:
        data.text || ""

    });


    // Keep history manageable

    if (
      chatHistory.length > 20
    ) {

      chatHistory =
        chatHistory.slice(-20);

    }

  }

  catch (error) {

    hideThinking();

    console.error(
      "Frontend error:",
      error
    );

    addMessage(
      "⚠️ Connection error. Please try again.",
      "ai"
    );

  }

}


